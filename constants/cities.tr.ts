/**
 * Türkiye şehirlerini alfabetik sıralı döndürür (duplicate'leri kaldırır)
 */
export function getTürkiyeCities(): string[] {
  return Array.from(new Set(TR_CITIES)).sort()
}

/**
 * Şehir adının geçerli olup olmadığını kontrol eder
 */
export function isValidTürkiyeCity(city: string | null | undefined): boolean {
  if (!city) return false
  return TR_CITIES.includes(city as any)
}

